#!/bin/sh
# Regenerate compose.yml from owners.conf (one service per owner, same image).
set -eu
. "$(dirname "$0")/_lib.sh"
need_instance
OUT=$BB/compose.yml.new
{
  echo "# GENERATED by bin/render-compose.sh from owners.conf. Do not edit by hand."
  echo "name: $PROJECT"
  echo "services:"
  grep -v '^\s*#' "$BB/owners.conf" | while read -r owner uid; do
    [ -n "${owner:-}" ] || continue
    cat <<YML
  $PREFIX-$owner:
    image: $IMAGE
    build: ./image
    container_name: $PREFIX-$owner
    restart: unless-stopped
    stop_grace_period: 20s
    user: "$uid:$uid"
    read_only: true
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    tmpfs: ["/tmp:size=16m,mode=1777"]
    environment:
      BB_OWNER: "$owner"
      FLUXER_INSTANCE: "$FLUXER_INSTANCE"
      LOG_LEVEL: "info"
    volumes:
      - ./owners/$owner:/cfg:ro
      - ./state/$owner:/state
    mem_limit: 512m
    pids_limit: 128
    logging:
      driver: json-file
      options: {max-size: "5m", max-file: "3"}
YML
  done
} > "$OUT"
mv "$OUT" "$BB/compose.yml"
